#!/usr/bin/env node
// generate-unknown-fields-fixtures.mjs
//
// Generates the unknown-member conformance fixtures under
// spec/vectors/unknown-fields/output/. These pin the normative rule in
// spec/manifest.md and spec/envelope.md: unknown members in the hashed
// documents (manifest.json, provenance/envelope.json, chain events) are
// preserved verbatim and included in canonicalization/hashing. A reader
// that projects the documents onto a fixed schema and re-serializes the
// projection for hashing silently drops the unknown members and diverges
// from what the signer signed — the exact bug class these fixtures catch.
//
// Fixtures:
//   unknown-fields.capsule
//       Plain capsule carrying `x-`-prefixed extension members in the
//       manifest, the envelope, and the single chain event — all present
//       at seal time and therefore covered by manifest_hash, the envelope
//       signature, and the event hash. MUST verify ok=true.
//   tampered-unknown-manifest-field.capsule
//       Same capsule with the manifest's `x-acme-policy` value mutated
//       post-seal. MUST fail with a manifest_hash mismatch.
//   tampered-unknown-envelope-field.capsule
//       Same capsule with the envelope's `x-acme-attestation` value
//       mutated post-seal. MUST fail envelope signature verification.
//   tampered-unknown-event-field.capsule
//       Same capsule with the first chain event's `x-acme-review-ticket`
//       value mutated post-seal. MUST fail the chain walk (and the
//       content index, which covers chain/events.jsonl).
//   keys.json
//       The originator keypair. FIXED intentional throwaway TEST keys —
//       never production keys — so regeneration is byte-stable
//       (deterministic Ed25519 + fixed timestamps + fixed ZIP date).
//
// Fixture -> expected outcome lives in
// spec/vectors/unknown-fields/vectors.json (the language-neutral
// registry); this script only (re)generates the capsule bytes.
// Regeneration is an intentional spec change; review the byte-level diff.
// Pass --check to compare generated bytes with the checked-in fixtures.

import { createPublicKey } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { jcs, hexToBytes, bytesToHex } from "../src/canonical.js";
import {
  ed25519PrivateFromRaw,
  ed25519PublicToRaw,
} from "../src/crypto.js";
import {
  buildChainEvents,
  eventsToJsonl,
  firstAndEntryHash,
} from "../src/chain.js";
import {
  buildContentIndex,
  buildManifest,
  computeCapsuleId,
  manifestBytes,
  manifestHash,
} from "../src/manifest.js";
import { buildEnvelope, signEnvelope } from "../src/envelope.js";
import { packZip, unpackZip } from "../src/zip.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..");
const OUT_DIR = join(REPO_ROOT, "spec", "vectors", "unknown-fields", "output");
const CHECK = process.argv.includes("--check");

// FIXED throwaway TEST key (deterministic fixtures). Never a production key.
const ORIGINATOR_PRIVATE_HEX =
  "9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60";

// Deterministic timestamps keep the fixtures byte-stable across regenerations.
const SIGNED_AT = "2026-07-01T12:00:00Z";

function originatorKeys() {
  const privateKey = Buffer.from(hexToBytes(ORIGINATOR_PRIVATE_HEX));
  const publicKey = ed25519PublicToRaw(
    createPublicKey(ed25519PrivateFromRaw(privateKey)),
  );
  return {
    privateKey,
    publicKey,
    privateKeyHex: ORIGINATOR_PRIVATE_HEX,
    publicKeyHex: bytesToHex(publicKey),
  };
}

/** Build the clean unknown-fields capsule (extension members signed over). */
async function buildUnknownFieldsCapsule(originator) {
  // One chain event carrying an unknown top-level member: covered by the
  // event hash (JCS over the preserved event minus `hash`).
  const events = buildChainEvents([
    {
      actor: "human:origin",
      kind: "decision",
      action: "approved",
      target: "program.md",
      timestamp: SIGNED_AT,
      payload: { note: "unknown-fields conformance fixture" },
      "x-acme-review-ticket": "ACME-1234",
    },
  ]);
  const { firstEventHash, entryHash } = firstAndEntryHash(events);

  const innerFiles = new Map();
  innerFiles.set(
    "program.md",
    Buffer.from("# Unknown Fields Fixture\n\nExtension members must survive verification.\n", "utf8"),
  );
  innerFiles.set("chain/events.jsonl", eventsToJsonl(events));

  const contentIndex = buildContentIndex(innerFiles);
  const capsuleId = computeCapsuleId(originator.publicKey, firstEventHash);

  const manifest = buildManifest({
    originator: { public_key: originator.publicKeyHex, label: "UnknownFieldsOriginator" },
    participants: [{ actor_id: "human:origin", role: "originator", label: "Origin" }],
    contentIndex,
    firstEventHash,
    skillTrust: {},
    encryption: null,
    createdAt: SIGNED_AT,
  });
  manifest.id = capsuleId;
  // Unknown manifest member: covered by manifest_hash (JCS over the whole
  // preserved manifest), which in turn sits inside the signed envelope.
  manifest["x-acme-policy"] = { tier: "gold", audit: true };
  const mfHash = manifestHash(manifest);

  const envelope = buildEnvelope({
    capsuleId,
    firstEventHash,
    entryHash,
    manifestHash: mfHash,
    contentIndexHash: contentIndex.index_hash,
    encryptedBlobHash: null,
    cipher: "none",
    signedAt: SIGNED_AT,
  });
  // Unknown envelope member: covered directly by the envelope signature
  // (JCS over the preserved envelope minus `signers`).
  envelope["x-acme-attestation"] = "urn:acme:attest:42";
  signEnvelope(envelope, [
    { role: "originator", publicKey: originator.publicKey, privateKey: originator.privateKey },
  ]);

  const allFiles = new Map(innerFiles);
  allFiles.set("manifest.json", manifestBytes(manifest));
  allFiles.set(
    "provenance/envelope.json",
    Buffer.from(JSON.stringify(envelope, null, 2), "utf8"),
  );
  return Buffer.from(await packZip(allFiles));
}

/** Rebuild a capsule ZIP with one inner JSON file mutated. */
async function rewriteJson(capsuleBytes, path, mutate, serialize) {
  const files = await unpackZip(capsuleBytes);
  if (!files.has(path)) throw new Error(`inner file not found: ${path}`);
  const doc = JSON.parse(Buffer.from(files.get(path)).toString("utf8"));
  mutate(doc);
  files.set(path, serialize(doc));
  return Buffer.from(await packZip(files));
}

/** Rebuild a capsule ZIP with one JSONL line's JSON mutated. */
async function rewriteJsonl(capsuleBytes, path, lineIndex, mutate) {
  const files = await unpackZip(capsuleBytes);
  if (!files.has(path)) throw new Error(`inner file not found: ${path}`);
  const lines = Buffer.from(files.get(path))
    .toString("utf8")
    .split("\n")
    .filter((l) => l.length > 0);
  const doc = JSON.parse(lines[lineIndex]);
  mutate(doc);
  lines[lineIndex] = JSON.stringify(doc);
  files.set(path, Buffer.from(lines.join("\n") + "\n", "utf8"));
  return Buffer.from(await packZip(files));
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  const originator = originatorKeys();

  const clean = await buildUnknownFieldsCapsule(originator);

  // Post-seal mutation of the unknown MANIFEST member. Only manifest.json
  // changes (it is outside the content index), so the failure signal is
  // precisely the manifest_hash mismatch against the signed envelope.
  const tamperedManifest = await rewriteJson(
    clean,
    "manifest.json",
    (m) => {
      m["x-acme-policy"].tier = "lead";
    },
    (m) => Buffer.from(jcs(m)),
  );

  // Post-seal mutation of the unknown ENVELOPE member. envelope.json is
  // outside the content index, so the failure signal is precisely the
  // envelope signature check.
  const tamperedEnvelope = await rewriteJson(
    clean,
    "provenance/envelope.json",
    (e) => {
      e["x-acme-attestation"] = "urn:acme:attest:43";
    },
    (e) => Buffer.from(JSON.stringify(e, null, 2), "utf8"),
  );

  // Post-seal mutation of the unknown CHAIN EVENT member. The event hash
  // no longer recomputes, and chain/events.jsonl is covered by the content
  // index, so both areas must fail.
  const tamperedEvent = await rewriteJsonl(clean, "chain/events.jsonl", 0, (e) => {
    e["x-acme-review-ticket"] = "ACME-9999";
  });

  const keys = {
    comment:
      "FIXED throwaway TEST keypair for deterministic conformance fixtures; never a production key.",
    originator: {
      publicKey: originator.publicKeyHex,
      privateKey: originator.privateKeyHex,
    },
  };

  const artifacts = [
    ["unknown-fields.capsule", clean],
    ["tampered-unknown-manifest-field.capsule", tamperedManifest],
    ["tampered-unknown-envelope-field.capsule", tamperedEnvelope],
    ["tampered-unknown-event-field.capsule", tamperedEvent],
    ["keys.json", Buffer.from(JSON.stringify(keys, null, 2) + "\n", "utf8")],
  ];

  for (const [name, bytes] of artifacts) {
    const path = join(OUT_DIR, name);
    if (CHECK) {
      let checkedIn;
      try {
        checkedIn = await readFile(path);
      } catch (err) {
        throw new Error(`${name}: checked-in fixture missing or unreadable: ${err.message}`);
      }
      if (!checkedIn.equals(bytes)) {
        throw new Error(`${name}: checked-in fixture differs from deterministic generator output`);
      }
      console.log(`ok ${name} (${bytes.length} bytes)`);
    } else {
      await writeFile(path, bytes);
      console.log(`wrote ${name} (${bytes.length} bytes)`);
    }
  }
  if (!CHECK) console.log(`\noriginator pubkey: ${originator.publicKeyHex}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
