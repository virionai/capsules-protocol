#!/usr/bin/env node
// generate-result-vocabulary-fixtures.mjs
//
// Generates the result-vocabulary conformance fixtures under
// spec/vectors/result-vocabulary/output/. These pin spec/results.md:
// the derived verdict (`valid` | `invalid` | `unsupported`), the
// verdict_reason channel (non-null iff unsupported), and the qualifier
// vocabulary — the weaker-claim facts a renderer must not hide,
// asserted as EXACT arrays so cross-lane emission cannot drift.
//
//   - unqualified-valid: the strongest honest shape (committed signer
//     set, bound actors, walked chain, matching allowlist) — the only
//     capsule allowed an empty qualifiers array.
//   - maximally-qualified-valid: the trust.md threat-table capsule (no
//     commitment, no participants, zero events, no allowlist) — valid,
//     with every applicable weaker-claim fact on the verdict.
//   - encrypted-outer: byte-copy of the tamper-detection clean
//     encrypted fixture — L2 carries encrypted_outer_only; the L3
//     result of the decrypted inner NEVER does.
//   - allowlist-no-match / policy-version-not-accepted: the same
//     unqualified bytes under different host configurations — the
//     host-relative qualifiers are facts about THIS verification.
//   - unsupported-newer / unsupported-older: verdict `unsupported` in
//     both refusal directions (a limitation of the verifier, not a
//     defect of the capsule).
//   - invalid-tamper: verdict `invalid`, no reason, no qualifiers.
//
// The private key is a FIXED intentional throwaway TEST key — never a
// production key — so regeneration is byte-stable. The encrypted
// fixture is a BYTE-COPY of ../tamper-detection/output/clean-encrypted
// (the established derivation pattern; fresh encryption would not be
// deterministic). Fixture -> expected outcome lives in
// spec/vectors/result-vocabulary/vectors.json. Pass --check to compare
// generated bytes with the checked-in fixtures.

import { createPublicKey } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { bytesToHex, concatBytes, hexToBytes, jcs, sha256 } from "../src/canonical.js";
import { ed25519PrivateFromRaw, ed25519PublicToRaw, ed25519Sign } from "../src/crypto.js";
import { buildChainEvents, eventsToJsonl, firstAndEntryHash } from "../src/chain.js";
import {
  buildContentIndex,
  buildManifest,
  buildSignerCommitment,
  computeCapsuleId,
  manifestBytes,
  manifestHash,
} from "../src/manifest.js";
import { buildEnvelope, signEnvelope } from "../src/envelope.js";
import { packZip, unpackZip } from "../src/zip.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..");
const OUT_DIR = join(REPO_ROOT, "spec", "vectors", "result-vocabulary", "output");
const TAMPER_DIR = join(REPO_ROOT, "spec", "vectors", "tamper-detection", "output");
const CHECK = process.argv.includes("--check");

// FIXED throwaway TEST keys (deterministic fixtures). Never production keys.
const ORIGINATOR_PRIVATE_HEX =
  "8e41c7a9052db6f3714c8e2a9d05b7f6023a1c8d4e5f6b70819a2c3d4e5f6a81";
// A keypair that signs NOTHING: the allowlist-no-match host configuration.
const STRANGER_PRIVATE_HEX =
  "17d2e4a6c8b0f3951e7d9b2a4c6e8f0113d5a7c9e1b3d5f70292b4d6e8fa1c35";

// Deterministic timestamp keeps the fixtures byte-stable across regenerations.
const SIGNED_AT = "2026-08-03T12:00:00Z";

function keysFromPrivateHex(privateKeyHex) {
  const privateKey = Buffer.from(hexToBytes(privateKeyHex));
  const publicKey = ed25519PublicToRaw(createPublicKey(ed25519PrivateFromRaw(privateKey)));
  return { privateKey, publicKey, privateKeyHex, publicKeyHex: bytesToHex(publicKey) };
}

/** The strongest honest shape: committed, bound, walked, signed. */
async function buildUnqualifiedCapsule(keys) {
  const events = buildChainEvents([
    {
      actor: "human:origin",
      kind: "decision",
      action: "approved",
      target: "program.md",
      timestamp: SIGNED_AT,
      payload: { note: "result-vocabulary conformance fixture" },
    },
  ]);
  const { firstEventHash, entryHash } = firstAndEntryHash(events);
  const files = new Map();
  files.set(
    "program.md",
    Buffer.from("# Result Vocabulary Fixture\n\nThe unqualified-valid shape.\n", "utf8"),
  );
  files.set("chain/events.jsonl", eventsToJsonl(events));
  const contentIndex = buildContentIndex(files);
  const manifest = buildManifest({
    originator: { public_key: keys.publicKeyHex, label: "ResultVocabOriginator" },
    participants: [{ actor_id: "human:origin", role: "originator", label: "Origin" }],
    contentIndex,
    firstEventHash,
    encryption: null,
    createdAt: SIGNED_AT,
    signerCommitment: buildSignerCommitment([
      { role: "originator", public_key: keys.publicKeyHex },
    ]),
  });
  manifest.id = computeCapsuleId(keys.publicKey, firstEventHash);
  const envelope = buildEnvelope({
    capsuleId: manifest.id,
    firstEventHash,
    entryHash,
    manifestHash: manifestHash(manifest),
    contentIndexHash: contentIndex.index_hash,
    encryptedBlobHash: null,
    cipher: "none",
    signedAt: SIGNED_AT,
  });
  signEnvelope(envelope, [
    { role: "originator", publicKey: keys.publicKey, privateKey: keys.privateKey },
  ]);
  const all = new Map(files);
  all.set("manifest.json", manifestBytes(manifest));
  all.set("provenance/envelope.json", Buffer.from(JSON.stringify(envelope, null, 2), "utf8"));
  return Buffer.from(await packZip(all));
}

/**
 * The trust.md threat-table capsule: zero events (null anchors), no
 * signer_commitment, no participants. Sealed by the originator, so it
 * VERIFIES — every reduced assurance is a reported fact, not a failure.
 * Bypasses the builder (whose backstop rule always emits an event).
 */
async function buildMaximallyQualifiedCapsule(keys) {
  const files = new Map();
  files.set(
    "program.md",
    Buffer.from("# Result Vocabulary Fixture\n\nThe weakest honest shape.\n", "utf8"),
  );
  files.set("chain/events.jsonl", Buffer.alloc(0));
  const contentIndex = buildContentIndex(files);
  const manifest = buildManifest({
    originator: { public_key: keys.publicKeyHex, label: "ResultVocabOriginator" },
    participants: [],
    contentIndex,
    firstEventHash: null,
    encryption: null,
    createdAt: SIGNED_AT,
  });
  manifest.id = computeCapsuleId(keys.publicKey, null);
  const envelope = buildEnvelope({
    capsuleId: manifest.id,
    firstEventHash: null,
    entryHash: null,
    manifestHash: manifestHash(manifest),
    contentIndexHash: contentIndex.index_hash,
    encryptedBlobHash: null,
    cipher: "none",
    signedAt: SIGNED_AT,
  });
  signEnvelope(envelope, [
    { role: "originator", publicKey: keys.publicKey, privateKey: keys.privateKey },
  ]);
  const all = new Map(files);
  all.set("manifest.json", manifestBytes(manifest));
  all.set("provenance/envelope.json", Buffer.from(JSON.stringify(envelope, null, 2), "utf8"));
  return Buffer.from(await packZip(all));
}

/**
 * A capsule declaring an arbitrary format version, internally coherent
 * under the declared version's domain strings — only the version gate
 * refuses it (the version-compat construction, reused so this
 * collection pins the verdict channel for both refusal directions).
 */
async function buildDeclaredVersionCapsule(keys, version) {
  const events = buildChainEvents([
    {
      actor: "human:origin",
      kind: "decision",
      action: "approved",
      target: "program.md",
      timestamp: SIGNED_AT,
      payload: { note: "result-vocabulary conformance fixture" },
    },
  ]);
  const { firstEventHash, entryHash } = firstAndEntryHash(events);
  const files = new Map();
  files.set(
    "program.md",
    Buffer.from(`# Result Vocabulary Fixture\n\nDeclares format version ${version}.\n`, "utf8"),
  );
  files.set("chain/events.jsonl", eventsToJsonl(events));
  const contentIndex = buildContentIndex(files);
  const manifest = buildManifest({
    originator: { public_key: keys.publicKeyHex, label: "ResultVocabOriginator" },
    participants: [{ actor_id: "human:origin", role: "originator", label: "Origin" }],
    contentIndex,
    firstEventHash,
    encryption: null,
    createdAt: SIGNED_AT,
    signerCommitment: buildSignerCommitment([
      { role: "originator", public_key: keys.publicKeyHex },
    ]),
  });
  manifest.format.version = version;
  manifest.id = bytesToHex(
    sha256(
      concatBytes(
        Buffer.from(`capsule-id-v${version}\x00`, "utf8"),
        keys.publicKey,
        hexToBytes(firstEventHash),
      ),
    ),
  );
  const envelope = buildEnvelope({
    capsuleId: manifest.id,
    firstEventHash,
    entryHash,
    manifestHash: manifestHash(manifest),
    contentIndexHash: contentIndex.index_hash,
    encryptedBlobHash: null,
    cipher: "none",
    signedAt: SIGNED_AT,
  });
  envelope.version = version;
  const { signers: _drop, ...payload } = envelope;
  const input = concatBytes(
    Buffer.from(`capsule-provenance-v${version}:originator\x00`, "utf8"),
    jcs(payload),
  );
  envelope.signers.push({
    role: "originator",
    public_key: keys.publicKeyHex,
    signature: bytesToHex(ed25519Sign(keys.privateKey, input)),
  });
  const all = new Map(files);
  all.set("manifest.json", manifestBytes(manifest));
  all.set("provenance/envelope.json", Buffer.from(JSON.stringify(envelope, null, 2), "utf8"));
  return Buffer.from(await packZip(all));
}

/** Post-seal content tamper: verdict `invalid`, no reason, no qualifiers. */
async function tamperProgram(capsuleBytes) {
  const files = await unpackZip(capsuleBytes);
  files.set("program.md", Buffer.from("# Result Vocabulary Fixture\n\nTAMPERED.\n", "utf8"));
  return Buffer.from(await packZip(files));
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  const originator = keysFromPrivateHex(ORIGINATOR_PRIVATE_HEX);
  const stranger = keysFromPrivateHex(STRANGER_PRIVATE_HEX);

  // Byte-copy of the checked-in clean encrypted fixture and its keys —
  // the semantic-binding derivation pattern (fresh encryption is not
  // deterministic; these bytes are effectively frozen in-repo).
  const encryptedBytes = await readFile(join(TAMPER_DIR, "clean-encrypted.capsule"));
  const tamperKeys = JSON.parse(await readFile(join(TAMPER_DIR, "keys.json"), "utf8"));

  const unqualified = await buildUnqualifiedCapsule(originator);

  const artifacts = [
    ["unqualified-valid.capsule", unqualified],
    ["maximally-qualified-valid.capsule", await buildMaximallyQualifiedCapsule(originator)],
    ["encrypted-outer.capsule", Buffer.from(encryptedBytes)],
    ["unsupported-newer.capsule", await buildDeclaredVersionCapsule(originator, "9.9")],
    ["unsupported-older.capsule", await buildDeclaredVersionCapsule(originator, "0.1")],
    ["invalid-tamper.capsule", await tamperProgram(unqualified)],
    [
      "keys.json",
      Buffer.from(
        JSON.stringify(
          {
            originator: {
              publicKey: originator.publicKeyHex,
              privateKey: originator.privateKeyHex,
            },
            stranger: {
              publicKey: stranger.publicKeyHex,
              privateKey: stranger.privateKeyHex,
            },
            // The clean-encrypted fixture's signer and recipient,
            // mirrored from ../tamper-detection/output/keys.json so the
            // collection's allowlist/decrypt names resolve locally.
            encrypted_originator: tamperKeys.originator,
            recipient: tamperKeys.recipient,
          },
          null,
          2,
        ) + "\n",
        "utf8",
      ),
    ],
  ];

  let drift = 0;
  for (const [name, bytes] of artifacts) {
    const path = join(OUT_DIR, name);
    if (CHECK) {
      let checkedIn;
      try {
        checkedIn = await readFile(path);
      } catch (err) {
        throw new Error(`${name}: checked-in fixture missing or unreadable: ${err.message}`);
      }
      if (!checkedIn.equals(bytes)) {
        console.error(`DRIFT: ${name} differs from deterministic generator output`);
        drift++;
      } else {
        console.log(`ok ${name}`);
      }
    } else {
      await writeFile(path, bytes);
      console.log(`wrote ${name} (${bytes.length} bytes)`);
    }
  }
  if (CHECK && drift > 0) {
    throw new Error(
      `${drift} result-vocabulary fixture(s) drifted; re-run the generator and review the diff`,
    );
  }
  if (CHECK) console.log("result-vocabulary fixtures: byte-stable");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
