#!/usr/bin/env node
// generate-version-compat-fixtures.mjs
//
// Generates the version-compatibility conformance fixtures under
// spec/vectors/version-compat/output/. These pin spec/versioning.md:
//
//   - A capsule declaring a KNOWN version verifies, and the verifier
//     REPORTS the observed version machine-readably.
//   - An unknown NEWER version fails closed with a verifier-too-old
//     diagnosis ("newer than this verifier supports") that is
//     distinguishable from tamper detection.
//   - An unknown OLDER version fails closed with its own reason
//     ("older than any version this verifier supports").
//   - A version string violating the <major>.<minor> grammar is a
//     malformed document (invalid_manifest_shape), not a support gap.
//   - envelope.version is gated identically to manifest.format.version.
//
// The unknown-version fixtures are INTERNALLY COHERENT under their
// declared version: capsule_id is derived with `capsule-id-v<V>\0` and
// the envelope is signed under `capsule-provenance-v<V>:<role>\0`, the
// domain strings a hypothetical v<V> verifier would reconstruct. From
// that verifier's point of view nothing is wrong with them — today's
// verifier must refuse them PURELY because the version is unknown,
// which is exactly the semantics the vectors pin.
//
// The private key is a FIXED intentional throwaway TEST key — never a
// production key — so regeneration is byte-stable (deterministic
// Ed25519 + fixed timestamps + fixed ZIP date). Fixture -> expected
// outcome lives in spec/vectors/version-compat/vectors.json. Pass
// --check to compare generated bytes with the checked-in fixtures.

import { createPublicKey } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { bytesToHex, concatBytes, hexToBytes, jcs, sha256 } from "../src/canonical.js";
import { ed25519PrivateFromRaw, ed25519PublicToRaw, ed25519Sign } from "../src/crypto.js";
import { buildChainEvents, eventsToJsonl, firstAndEntryHash } from "../src/chain.js";
import {
  buildContentIndex,
  buildManifest,
  buildSignerCommitment,
  manifestBytes,
  manifestHash,
} from "../src/manifest.js";
import { buildEnvelope } from "../src/envelope.js";
import { CapsuleBuilder } from "../src/builder.js";
import { packZip } from "../src/zip.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..");
const OUT_DIR = join(REPO_ROOT, "spec", "vectors", "version-compat", "output");
const CHECK = process.argv.includes("--check");

// FIXED throwaway TEST key (deterministic fixtures). Never a production key.
const PRIVATE_HEX = "d4c1a02b7e95f8331c60b2ae44f7d5980e3ab6c15d92e7f04a8b3c6d51e90f28";

// Deterministic timestamps keep the fixtures byte-stable across regenerations.
const SIGNED_AT = "2026-08-01T12:00:00Z";

function keysFromPrivateHex(privateKeyHex) {
  const privateKey = Buffer.from(hexToBytes(privateKeyHex));
  const publicKey = ed25519PublicToRaw(createPublicKey(ed25519PrivateFromRaw(privateKey)));
  return { privateKey, publicKey, privateKeyHex, publicKeyHex: bytesToHex(publicKey) };
}

/** Positive control: a capsule sealed by the SDK at the current version. */
async function buildCurrentCapsule(keys) {
  const builder = new CapsuleBuilder({
    originator: { publicKey: keys.publicKeyHex, label: "VersionCompatOriginator" },
    participants: [{ actor_id: "human:origin", role: "originator", label: "Origin" }],
    createdAt: SIGNED_AT,
  });
  builder.setProgram("# Version Compat Fixture\n\nSealed at the current version.\n");
  builder.appendEvent({
    actor: "human:origin",
    kind: "decision",
    action: "approved",
    target: "program.md",
    timestamp: SIGNED_AT,
    payload: { note: "version-compat conformance fixture" },
  });
  const bytes = await builder.seal({
    signers: [{ role: "originator", publicKey: keys.publicKey, privateKey: keys.privateKey }],
    signedAt: SIGNED_AT,
  });
  return Buffer.from(bytes);
}

/**
 * A capsule that DECLARES `manifestVersion` / `envelopeVersion`,
 * internally coherent under the declared versions' domain strings. The
 * domains are hand-rolled here ON PURPOSE: the fixtures must pin the
 * spec's version-keyed strings, not whatever the SDK's helpers emit.
 */
async function buildDeclaredVersionCapsule({ keys, manifestVersion, envelopeVersion }) {
  const events = buildChainEvents([
    {
      actor: "human:origin",
      kind: "decision",
      action: "approved",
      target: "program.md",
      timestamp: SIGNED_AT,
      payload: { note: "version-compat conformance fixture" },
    },
  ]);
  const { firstEventHash, entryHash } = firstAndEntryHash(events);
  const files = new Map();
  files.set(
    "program.md",
    Buffer.from(`# Version Compat Fixture\n\nDeclares format version ${manifestVersion}.\n`, "utf8"),
  );
  files.set("chain/events.jsonl", eventsToJsonl(events));
  const contentIndex = buildContentIndex(files);
  const manifest = buildManifest({
    originator: { public_key: keys.publicKeyHex, label: "VersionCompatOriginator" },
    participants: [{ actor_id: "human:origin", role: "originator", label: "Origin" }],
    contentIndex,
    firstEventHash,
    skillTrust: {},
    encryption: null,
    createdAt: SIGNED_AT,
    signerCommitment: buildSignerCommitment([
      { role: "originator", public_key: keys.publicKeyHex },
    ]),
  });
  manifest.format.version = manifestVersion;
  manifest.id = bytesToHex(
    sha256(
      concatBytes(
        Buffer.from(`capsule-id-v${manifestVersion}\x00`, "utf8"),
        keys.publicKey,
        hexToBytes(firstEventHash),
      ),
    ),
  );
  const envelope = buildEnvelope({
    capsuleId: manifest.id,
    firstEventHash,
    entryHash,
    manifestHash: manifestHash(manifest),
    contentIndexHash: contentIndex.index_hash,
    encryptedBlobHash: null,
    cipher: "none",
    signedAt: SIGNED_AT,
  });
  envelope.version = envelopeVersion;
  const { signers: _drop, ...payload } = envelope;
  const input = concatBytes(
    Buffer.from(`capsule-provenance-v${envelopeVersion}:originator\x00`, "utf8"),
    jcs(payload),
  );
  envelope.signers.push({
    role: "originator",
    public_key: keys.publicKeyHex,
    signature: bytesToHex(ed25519Sign(keys.privateKey, input)),
  });
  const all = new Map(files);
  all.set("manifest.json", manifestBytes(manifest));
  all.set("provenance/envelope.json", Buffer.from(JSON.stringify(envelope, null, 2), "utf8"));
  return Buffer.from(await packZip(all));
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  const keys = keysFromPrivateHex(PRIVATE_HEX);

  const artifacts = [
    ["known-current-version.capsule", await buildCurrentCapsule(keys)],
    [
      "unknown-newer-version.capsule",
      await buildDeclaredVersionCapsule({ keys, manifestVersion: "9.9", envelopeVersion: "9.9" }),
    ],
    [
      "unknown-older-version.capsule",
      await buildDeclaredVersionCapsule({ keys, manifestVersion: "0.1", envelopeVersion: "0.1" }),
    ],
    [
      "version-not-a-version.capsule",
      await buildDeclaredVersionCapsule({
        keys,
        manifestVersion: "banana",
        envelopeVersion: "banana",
      }),
    ],
    [
      "envelope-version-newer.capsule",
      await buildDeclaredVersionCapsule({ keys, manifestVersion: "0.6", envelopeVersion: "9.9" }),
    ],
    [
      "keys.json",
      Buffer.from(
        JSON.stringify(
          { originator: { publicKey: keys.publicKeyHex, privateKey: keys.privateKeyHex } },
          null,
          2,
        ) + "\n",
        "utf8",
      ),
    ],
  ];

  let drift = 0;
  for (const [name, bytes] of artifacts) {
    const path = join(OUT_DIR, name);
    if (CHECK) {
      let checkedIn;
      try {
        checkedIn = await readFile(path);
      } catch (err) {
        throw new Error(`${name}: checked-in fixture missing or unreadable: ${err.message}`);
      }
      if (!checkedIn.equals(bytes)) {
        console.error(`DRIFT: ${name} differs from deterministic generator output`);
        drift++;
      } else {
        console.log(`ok ${name}`);
      }
    } else {
      await writeFile(path, bytes);
      console.log(`wrote ${name} (${bytes.length} bytes)`);
    }
  }
  if (CHECK && drift > 0) {
    throw new Error(
      `${drift} version-compat fixture(s) drifted; re-run the generator and review the diff`,
    );
  }
  if (CHECK) console.log("version-compat fixtures: byte-stable");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
