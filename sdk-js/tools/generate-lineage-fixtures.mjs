#!/usr/bin/env node
// generate-lineage-fixtures.mjs
//
// Generates the lineage conformance fixtures under
// spec/vectors/lineage/output/. These pin the normative rules in
// spec/lineage.md (`manifest.predecessors`):
//
//   - Standalone checks fail closed on a PRESENT malformed declaration
//     with shared `predecessors[i].<member>` diagnoses;
//   - identity coherence is era-keyed and SKIPPED (reported, never
//     failed) for unknown declared eras;
//   - linkage against supplied predecessor bytes is REPORT-ONLY (the
//     ok:true-under-mismatch anti-framing pin), with the closed entry
//     status vocabulary and the era-keyed recursive walk;
//   - the deliberate ABSENCE of a self-reference rule (same-key
//     zero-event rewrap);
//   - the default-profile scope (unsupported_profile linkage reason)
//     and the plain-predecessor scope (encrypted_predecessor);
//   - the inner/outer both-present equality for encrypted successors.
//
// Every successor fixture is built through the BUILDER path
// (CapsuleBuilder.continueFrom / rewrapCapsule), so the checked-in
// vectors are themselves the cross-lane pin of rewrap output — a
// writer's conformance surface is its outputs. Low-level construction
// appears only where the builder correctly refuses to produce the
// shape (malformed declarations, zero-event chains, split inner/outer
// placements, deterministic encryption).
//
// The frozen v0.6 predecessor is a BYTE-IDENTICAL COPY of
// spec/vectors/version-compat/output/known-previous-version-0.6.capsule
// — never regenerated, never resealed. --check asserts byte equality
// with the version-compat original (and with the checked-in copy).
//
// The private keys are FIXED intentional throwaway TEST keys — never
// production keys — so regeneration is byte-stable (deterministic
// Ed25519, fixed timestamps, fixed ZIP date, and FIXED test-only
// encryption randomness for the two encrypted fixtures). Fixture →
// expected outcome lives in spec/vectors/lineage/vectors.json.
// Regeneration is an intentional spec change; review the byte-level
// diff. Pass --check to compare generated bytes with the checked-in
// fixtures.

