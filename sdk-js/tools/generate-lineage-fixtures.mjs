function ed25519FromPrivateHex(privateKeyHex) {
  const privateKey = Buffer.from(hexToBytes(privateKeyHex));
  const publicKey = ed25519PublicToRaw(createPublicKey(ed25519PrivateFromRaw(privateKey)));
  return { privateKey, publicKey, privateKeyHex, publicKeyHex: bytesToHex(publicKey) };
}

function x25519FromPrivateHex(privateKeyHex) {
  const privateKey = Buffer.from(hexToBytes(privateKeyHex));
  const publicKey = x25519PublicToRaw(createPublicKey(x25519PrivateFromRaw(privateKey)));
  return { privateKey, publicKey, privateKeyHex, publicKeyHex: bytesToHex(publicKey) };
}

function signerOf(keys, role = "originator") {
  return { role, publicKey: keys.publicKey, privateKey: keys.privateKey };
}

/** The root predecessor line: Alice's worked capsule (optionally longer). */
function alicePredecessorBuilder(alice, events = 3) {
  const builder = new CapsuleBuilder({
    originator: { publicKey: alice.publicKeyHex, label: "Alice" },
    participants: [
      { actor_id: "human:alice", role: "originator" },
      { actor_id: "ai:assistant", role: "advisor" },
    ],
    createdAt: T_PRED,
  });
  builder.setProgram("# Shared Analysis\n\nAlice's line of work.\n");
  builder.setAgents("# Agents\n- human:alice (originator)\n- ai:assistant (advisor)\n");
  builder.addPayload("payload/data.csv", Buffer.from("k,v\nrate,0.07\n", "utf8"));
  const actions = ["scoped", "analyzed", "approved", "extended"];
  for (let i = 0; i < events; i++) {
    builder.appendEvent({
      actor: i % 2 === 0 ? "human:alice" : "ai:assistant",
      kind: i === 2 ? "decision" : "observation",
      action: actions[i],
      target: "program.md",
      timestamp: T_PRED,
      payload: { note: `lineage conformance fixture event ${i + 1}` },
    });
  }
  return builder;
}

/**
 * Low-level plain capsule sealed WITH an arbitrary predecessors value —
 * the builder rightly refuses to emit these shapes, and the fixtures
 * must be SIGNED so only the lineage checks fail.
 */
async function sealWithPredecessors(keys, predecessorsValue, { mutateManifest } = {}) {
  const events = buildChainEvents([{
    actor: "human:alice",
    kind: "observation",
    action: "noted",
    target: "capsule",
    timestamp: T_PRED,
    payload: { note: "lineage conformance fixture" },
  }]);
  const { firstEventHash, entryHash } = firstAndEntryHash(events);
  const files = new Map();
  files.set("program.md", Buffer.from("# Lineage Fixture\n", "utf8"));
  files.set("chain/events.jsonl", eventsToJsonl(events));
  const contentIndex = buildContentIndex(files);
  const manifest = buildManifest({
    originator: { public_key: keys.publicKeyHex, label: "Fixture" },
    participants: [{ actor_id: "human:alice", role: "originator" }],
    contentIndex,
    firstEventHash,
    encryption: null,
    createdAt: T_PRED,
    signerCommitment: buildSignerCommitment([
      { role: "originator", public_key: keys.publicKeyHex },
    ]),
  });
  if (predecessorsValue !== undefined) manifest.predecessors = predecessorsValue;
  if (mutateManifest) mutateManifest(manifest);
  manifest.id = computeCapsuleId(keys.publicKey, firstEventHash);
  const envelope = buildEnvelope({
    capsuleId: manifest.id,
    firstEventHash,
    entryHash,
    manifestHash: manifestHash(manifest),
    contentIndexHash: contentIndex.index_hash,
    encryptedBlobHash: null,
    cipher: "none",
    signedAt: T_PRED,
  });
  signEnvelope(envelope, [signerOf(keys)]);
  const all = new Map(files);
  all.set("manifest.json", manifestBytes(manifest));
  all.set("provenance/envelope.json", Buffer.from(JSON.stringify(envelope, null, 2), "utf8"));
  return Buffer.from(await packZip(all));
}

