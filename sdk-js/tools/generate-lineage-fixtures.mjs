  const alice = ed25519FromPrivateHex(PRIVATE_HEX.alice);
  const bob = ed25519FromPrivateHex(PRIVATE_HEX.bob);
  const carol = ed25519FromPrivateHex(PRIVATE_HEX.carol);
  const dana = ed25519FromPrivateHex(PRIVATE_HEX.dana);
  const attacker = ed25519FromPrivateHex(PRIVATE_HEX.attacker);
  const recipient = x25519FromPrivateHex(PRIVATE_HEX.recipient);

