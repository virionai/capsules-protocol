#!/usr/bin/env node
// generate-chain-binding-fixtures.mjs
//
// Generates the chain-binding conformance fixtures under
// spec/vectors/chain-binding/output/. These pin the normative rules in
// spec/chain.md ("Empty chains", "Unknown members") and
// spec/envelope.md (`first_event_hash` / `entry_hash` field rules):
//
//   - An EMPTY chain (zero events) is legal — the weakest honest shape,
//     e.g. a template or draft capsule. Its three anchor claims
//     (manifest.first_event_hash, envelope.first_event_hash,
//     envelope.entry_hash) MUST all be null, and capsule_id derives
//     with 32 zero bytes standing in for first_event_hash_raw.
//   - A capsule claiming ANY chain anchor while carrying zero events is
//     lying about its own bytes. Verifiers MUST reject it fail-closed:
//     in a plain capsule those anchors are the only envelope-to-chain
//     binding, so skipping the comparison verifies an unbound capsule.
//   - The per-event hash preimage is rebuilt from the STORED line, so
//     an event whose bytes omit the optional `untrusted_payload_fields`
//     member must verify. A verifier that re-serializes a typed
//     projection injects the field's default, flips the JCS bytes, and
//     spuriously fails an intact chain.
//
// Fixtures:
//   empty-chain-null-anchors.capsule    zero events, all anchors null,
//                                       originator-signed + committed. ok=true.
//   empty-chain-claimed-anchors.capsule zero events but manifest + envelope
//                                       claim anchors (consistently, so the
//                                       capsule_id derivation is self-
//                                       consistent and ONLY the empty-chain
//                                       rule fires). FAIL.
//   event-without-untrusted-fields.capsule  one event whose stored bytes
//                                       omit untrusted_payload_fields. ok=true.
//   keys.json                           originator keypair.
//
// The private key is a FIXED intentional throwaway TEST key — never a
// production key — so regeneration is byte-stable (deterministic Ed25519
// + fixed timestamps + fixed ZIP date). Fixture -> expected outcome
// lives in spec/vectors/chain-binding/vectors.json. Regeneration is an
// intentional spec change; review the byte-level diff. Pass --check to
// compare generated bytes with the checked-in fixtures.

import { createPublicKey } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { hexToBytes, bytesToHex } from "../src/canonical.js";
import { ed25519PrivateFromRaw, ed25519PublicToRaw } from "../src/crypto.js";
import { hashEvent, eventsToJsonl } from "../src/chain.js";
import {
  buildContentIndex,
  buildManifest,
  buildSignerCommitment,
  computeCapsuleId,
  manifestBytes,
  manifestHash,
} from "../src/manifest.js";
import { buildEnvelope, signEnvelope } from "../src/envelope.js";
import { packZip } from "../src/zip.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..");
const OUT_DIR = join(REPO_ROOT, "spec", "vectors", "chain-binding", "output");
const CHECK = process.argv.includes("--check");

// FIXED throwaway TEST key (deterministic fixtures). Never a production key.
const ORIGINATOR_PRIVATE_HEX =
  "d1c2b5a4837a9e60f3b8a12c45de07f6912b3c84d5e6f7a8091b2c3d4e5f6071";

// Deterministic timestamp keeps the fixtures byte-stable across regenerations.
const SIGNED_AT = "2026-08-02T12:00:00Z";

function keysFromPrivateHex(privateKeyHex) {
  const privateKey = Buffer.from(hexToBytes(privateKeyHex));
  const publicKey = ed25519PublicToRaw(createPublicKey(ed25519PrivateFromRaw(privateKey)));
  return { privateKey, publicKey, privateKeyHex, publicKeyHex: bytesToHex(publicKey) };
}

/**
 * Low-level sealed plain capsule; bypasses the builder (whose backstop
 * rule always emits an event, so it can never produce the zero-event
 * shape). `chainBytes` are stored verbatim as chain/events.jsonl.
 */
async function sealCapsule(keys, { chainBytes, manifestFirstEventHash, firstEventHash, entryHash, program }) {
  const files = new Map();
  files.set("program.md", Buffer.from(program, "utf8"));
  files.set("chain/events.jsonl", chainBytes);
  const contentIndex = buildContentIndex(files);
  const manifest = buildManifest({
    originator: { public_key: keys.publicKeyHex, label: "ChainBindingFixture" },
    participants: [{ actor_id: "human:origin", role: "originator", label: "Origin" }],
    contentIndex,
    firstEventHash: manifestFirstEventHash,
    skillTrust: {},
    encryption: null,
    createdAt: SIGNED_AT,
    signerCommitment: buildSignerCommitment([
      { role: "originator", public_key: keys.publicKeyHex },
    ]),
  });
  manifest.id = computeCapsuleId(keys.publicKey, manifestFirstEventHash);
  const envelope = buildEnvelope({
    capsuleId: manifest.id,
    firstEventHash,
    entryHash,
    manifestHash: manifestHash(manifest),
    contentIndexHash: contentIndex.index_hash,
    encryptedBlobHash: null,
    cipher: "none",
    signedAt: SIGNED_AT,
  });
  signEnvelope(envelope, [
    { role: "originator", publicKey: keys.publicKey, privateKey: keys.privateKey },
  ]);
  const all = new Map(files);
  all.set("manifest.json", manifestBytes(manifest));
  all.set("provenance/envelope.json", Buffer.from(JSON.stringify(envelope, null, 2), "utf8"));
  return Buffer.from(await packZip(all));
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  const originator = keysFromPrivateHex(ORIGINATOR_PRIVATE_HEX);

  // (1) Positive control: zero events, all three anchors null. The
  // weakest honest shape MUST verify.
  const nullAnchors = await sealCapsule(originator, {
    chainBytes: Buffer.alloc(0),
    manifestFirstEventHash: null,
    firstEventHash: null,
    entryHash: null,
    program: "# Chain Binding Fixture\n\nDraft capsule: no events yet.\n",
  });

  // (2) The lie: zero events, but manifest + envelope claim anchors.
  // The claims are internally CONSISTENT (manifest.first_event_hash
  // feeds the capsule_id derivation, and the envelope repeats it), so
  // every other check passes and the empty-chain rule is the only
  // thing standing. The claimed values are deterministic hashes of a
  // phantom event that was never stored.
  const phantom = {
    seq: 1,
    event_id: "evt_001",
    actor: "human:origin",
    kind: "decision",
    action: "approved",
    target: "program.md",
    timestamp: SIGNED_AT,
    payload: { note: "phantom event: hashed, then never stored" },
    prev_hash: "0".repeat(64),
  };
  const phantomHash = bytesToHex(hashEvent(phantom));
  const claimedAnchors = await sealCapsule(originator, {
    chainBytes: Buffer.alloc(0),
    manifestFirstEventHash: phantomHash,
    firstEventHash: phantomHash,
    entryHash: phantomHash,
    program: "# Chain Binding Fixture\n\nClaims a chain it does not carry.\n",
  });

  // (3) Stored-line hashing: one event whose bytes OMIT the optional
  // untrusted_payload_fields member. Must verify — the hash preimage is
  // the stored line, not a typed-struct round-trip.
  const bare = {
    seq: 1,
    event_id: "evt_001",
    actor: "human:origin",
    kind: "decision",
    action: "approved",
    target: "program.md",
    timestamp: SIGNED_AT,
    payload: { note: "stored without untrusted_payload_fields" },
    prev_hash: "0".repeat(64),
  };
  bare.hash = bytesToHex(hashEvent({ ...bare }));
  const withoutUntrusted = await sealCapsule(originator, {
    chainBytes: eventsToJsonl([bare]),
    manifestFirstEventHash: bare.hash,
    firstEventHash: bare.hash,
    entryHash: bare.hash,
    program: "# Chain Binding Fixture\n\nEvent omits untrusted_payload_fields.\n",
  });

  const keys = {
    originator: {
      publicKey: originator.publicKeyHex,
      privateKey: originator.privateKeyHex,
    },
  };

  const artifacts = [
    ["empty-chain-null-anchors.capsule", nullAnchors],
    ["empty-chain-claimed-anchors.capsule", claimedAnchors],
    ["event-without-untrusted-fields.capsule", withoutUntrusted],
    ["keys.json", Buffer.from(JSON.stringify(keys, null, 2) + "\n", "utf8")],
  ];

  let drift = 0;
  for (const [name, bytes] of artifacts) {
    const path = join(OUT_DIR, name);
    if (CHECK) {
      let checkedIn;
      try {
        checkedIn = await readFile(path);
      } catch (err) {
        throw new Error(`${name}: checked-in fixture missing or unreadable: ${err.message}`);
      }
      if (!checkedIn.equals(bytes)) {
        console.error(`DRIFT: ${name} differs from deterministic generator output`);
        drift++;
      } else {
        console.log(`ok ${name}`);
      }
    } else {
      await writeFile(path, bytes);
      console.log(`wrote ${name} (${bytes.length} bytes)`);
    }
  }
  if (CHECK && drift > 0) {
    throw new Error(`${drift} chain-binding fixture(s) drifted; re-run the generator and review the diff`);
  }
  if (CHECK) console.log("chain-binding fixtures: byte-stable");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
