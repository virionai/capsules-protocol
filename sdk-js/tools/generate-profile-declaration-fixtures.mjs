#!/usr/bin/env node
// generate-profile-declaration-fixtures.mjs
//
// Generates the profile-declaration conformance fixtures under
// spec/vectors/profile-declaration/output/. These pin spec/profiles.md:
//
//   - ABSENCE of a declaration in a 0.6/0.7 capsule means the default
//     profile `v0.6-suite`/`1.0`, permanently; explicit declaration of
//     the default is legal and exactly equivalent to absence, in both
//     documents or (via normalization) in one.
//   - A declared (id, version) pair outside the verifier's table is
//     refused at open with `unsupported_profile` — a limitation of the
//     verifier, not a defect of the capsule.
//   - Normalized manifest/envelope declarations that disagree are
//     refused with `profile_mismatch`, BEFORE any table lookup.
//   - A present declaration violating the closed object shape or the
//     identifier grammar is a MALFORMED document (invalid_manifest_shape).
//   - The version gate runs first: an unknown-version capsule reports
//     its declaration with profile status `unevaluated`.
//   - Only the reserved members have force: an `x-` manifest member
//     with a profile-ish name is inert.
//   - Declarations are sealed bytes: stripping one post-seal is tamper.
//
// Every negative fixture is INTERNALLY COHERENT under default rules
// except for the declaration under test — capsule_id derives under the
// declared era's id domain and the envelope is signed (declaration
// included in the payload) under the era's provenance domain — so ONLY
// the profile gate can be the thing refusing it. A lane that ignores
// the gate verifies the fixture ok=true and fails the registry: each
// negative vector is simultaneously the anti-silent-downgrade pin.
//
// The private key is a FIXED intentional throwaway TEST key — never a
// production key — so regeneration is byte-stable (deterministic
// Ed25519 + fixed timestamps + fixed ZIP date). Fixture -> expected
// outcome lives in spec/vectors/profile-declaration/vectors.json. Pass
// --check to compare generated bytes with the checked-in fixtures.

import { createPublicKey } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { bytesToHex, concatBytes, hexToBytes, jcs, parseJsonStrict, sha256 } from "../src/canonical.js";
import { ed25519PrivateFromRaw, ed25519PublicToRaw, ed25519Sign } from "../src/crypto.js";
import { buildChainEvents, eventsToJsonl, firstAndEntryHash } from "../src/chain.js";
import {
  buildContentIndex,
  buildManifest,
  buildSignerCommitment,
  manifestBytes,
  manifestHash,
} from "../src/manifest.js";
import { buildEnvelope } from "../src/envelope.js";
import { packZip, unpackZip } from "../src/zip.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..");
const OUT_DIR = join(REPO_ROOT, "spec", "vectors", "profile-declaration", "output");
const CHECK = process.argv.includes("--check");

// FIXED throwaway TEST key (deterministic fixtures). Never a production key.
const PRIVATE_HEX = "5f2ab8d10c47e6b3928d1f04a7c5e6903b8d2a71f45c09e6d3b7a20481c5f9e2";

// Deterministic timestamps keep the fixtures byte-stable across regenerations.
const SIGNED_AT = "2026-08-03T12:00:00Z";

function keysFromPrivateHex(privateKeyHex) {
  const privateKey = Buffer.from(hexToBytes(privateKeyHex));
  const publicKey = ed25519PublicToRaw(createPublicKey(ed25519PrivateFromRaw(privateKey)));
  return { privateKey, publicKey, privateKeyHex, publicKeyHex: bytesToHex(publicKey) };
}

/**
 * A capsule internally coherent under its DECLARED version's default-
 * rule domain strings, carrying the given profile declarations (and
 * optionally an extra unprefixed-adjacent manifest member). The
 * declarations sit inside the manifest bytes (covered by manifest_hash)
 * and inside the signed envelope payload — the domains are hand-rolled
 * so the fixtures pin the spec's strings, not the SDK's helpers.
 */
async function buildDeclaredProfileCapsule({
  keys,
  version = "0.7",
  manifestProfile,
  envelopeProfile,
  extraManifestMembers,
}) {
  const events = buildChainEvents([
    {
      actor: "human:origin",
      kind: "decision",
      action: "approved",
      target: "program.md",
      timestamp: SIGNED_AT,
      payload: { note: "profile-declaration conformance fixture" },
    },
  ]);
  const { firstEventHash, entryHash } = firstAndEntryHash(events);
  const files = new Map();
  files.set(
    "program.md",
    Buffer.from(`# Profile Declaration Fixture\n\nDeclares format version ${version}.\n`, "utf8"),
  );
  files.set("chain/events.jsonl", eventsToJsonl(events));
  const contentIndex = buildContentIndex(files);
  const manifest = buildManifest({
    originator: { public_key: keys.publicKeyHex, label: "ProfileDeclOriginator" },
    participants: [{ actor_id: "human:origin", role: "originator", label: "Origin" }],
    contentIndex,
    firstEventHash,
    encryption: null,
    createdAt: SIGNED_AT,
    signerCommitment: buildSignerCommitment([
      { role: "originator", public_key: keys.publicKeyHex },
    ]),
  });
  manifest.format.version = version;
  if (manifestProfile !== undefined) manifest.format.profile = manifestProfile;
  if (extraManifestMembers) Object.assign(manifest, extraManifestMembers);
  manifest.id = bytesToHex(
    sha256(
      concatBytes(
        Buffer.from(`capsule-id-v${version}\x00`, "utf8"),
        keys.publicKey,
        hexToBytes(firstEventHash),
      ),
    ),
  );
  const envelope = buildEnvelope({
    capsuleId: manifest.id,
    firstEventHash,
    entryHash,
    manifestHash: manifestHash(manifest),
    contentIndexHash: contentIndex.index_hash,
    encryptedBlobHash: null,
    cipher: "none",
    signedAt: SIGNED_AT,
  });
  envelope.version = version;
  if (envelopeProfile !== undefined) envelope.profile = envelopeProfile;
  // The declaration is INSIDE the signed payload: JCS(envelope minus signers).
  const { signers: _drop, ...payload } = envelope;
  const input = concatBytes(
    Buffer.from(`capsule-provenance-v${version}:originator\x00`, "utf8"),
    jcs(payload),
  );
  envelope.signers.push({
    role: "originator",
    public_key: keys.publicKeyHex,
    signature: bytesToHex(ed25519Sign(keys.privateKey, input)),
  });
  const all = new Map(files);
  all.set("manifest.json", manifestBytes(manifest));
  all.set("provenance/envelope.json", Buffer.from(JSON.stringify(envelope, null, 2), "utf8"));
  return Buffer.from(await packZip(all));
}

/**
 * Post-seal tamper: strip manifest.format.profile from a sealed capsule
 * WITHOUT re-deriving anything. The declaration is sealed bytes —
 * removing it must surface as a manifest_hash mismatch, never as a
 * clean "undeclared" capsule.
 */
async function stripManifestDeclaration(capsuleBytes) {
  const files = await unpackZip(capsuleBytes);
  const manifest = parseJsonStrict(files.get("manifest.json"), "manifest.json");
  delete manifest.format.profile;
  files.set("manifest.json", manifestBytes(manifest));
  return Buffer.from(await packZip(files));
}

const DEFAULT_DECL = { id: "v0.6-suite", version: "1.0" };
const VENDOR_DECL = { id: "x-test-kms-1", version: "1.0" };

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  const keys = keysFromPrivateHex(PRIVATE_HEX);
  const build = (opts) => buildDeclaredProfileCapsule({ keys, ...opts });

  const explicitDefault = await build({
    manifestProfile: DEFAULT_DECL,
    envelopeProfile: DEFAULT_DECL,
  });

  const artifacts = [
    ["absent-profile-is-default.capsule", await build({})],
    ["explicit-default-equivalent.capsule", explicitDefault],
    ["explicit-default-one-document.capsule", await build({ manifestProfile: DEFAULT_DECL })],
    [
      "unsupported-vendor-profile.capsule",
      await build({ manifestProfile: VENDOR_DECL, envelopeProfile: VENDOR_DECL }),
    ],
    [
      "unsupported-default-profile-version.capsule",
      await build({
        manifestProfile: { id: "v0.6-suite", version: "9.9" },
        envelopeProfile: { id: "v0.6-suite", version: "9.9" },
      }),
    ],
    [
      "unsupported-profile-0.6-era.capsule",
      await build({ version: "0.6", manifestProfile: VENDOR_DECL, envelopeProfile: VENDOR_DECL }),
    ],
    [
      "profile-mismatch-value.capsule",
      await build({ manifestProfile: VENDOR_DECL, envelopeProfile: DEFAULT_DECL }),
    ],
    ["profile-mismatch-presence.capsule", await build({ manifestProfile: VENDOR_DECL })],
    ["profile-invalid-null.capsule", await build({ manifestProfile: null })],
    ["profile-invalid-not-object.capsule", await build({ manifestProfile: "v0.6-suite" })],
    [
      "profile-invalid-id-grammar.capsule",
      await build({ manifestProfile: { id: "Acme KMS!", version: "1.0" } }),
    ],
    [
      "profile-unknown-member-in-object.capsule",
      await build({
        manifestProfile: { id: "v0.6-suite", version: "1.0", critical: ["id"] },
      }),
    ],
    [
      "profile-params-in-envelope.capsule",
      await build({
        manifestProfile: {
          id: "v0.6-suite",
          version: "1.0",
          params: { issuer: "https://capsules.test.example" },
        },
        envelopeProfile: {
          id: "v0.6-suite",
          version: "1.0",
          params: { issuer: "https://capsules.test.example" },
        },
      }),
    ],
    [
      "unknown-version-profile-unevaluated.capsule",
      await build({ version: "9.9", manifestProfile: VENDOR_DECL, envelopeProfile: VENDOR_DECL }),
    ],
    [
      "x-member-named-like-profile-is-inert.capsule",
      await build({
        extraManifestMembers: { "x-test-profile": { id: "x-acme-kms", version: "1.0" } },
      }),
    ],
    ["profile-declaration-tampered.capsule", await stripManifestDeclaration(explicitDefault)],
    [
      "keys.json",
      Buffer.from(
        JSON.stringify(
          { originator: { publicKey: keys.publicKeyHex, privateKey: keys.privateKeyHex } },
          null,
          2,
        ) + "\n",
        "utf8",
      ),
    ],
  ];

  let drift = 0;
  for (const [name, bytes] of artifacts) {
    const path = join(OUT_DIR, name);
    if (CHECK) {
      let checkedIn;
      try {
        checkedIn = await readFile(path);
      } catch (err) {
        throw new Error(`${name}: checked-in fixture missing or unreadable: ${err.message}`);
      }
      if (!checkedIn.equals(bytes)) {
        console.error(`DRIFT: ${name} differs from deterministic generator output`);
        drift++;
      } else {
        console.log(`ok ${name}`);
      }
    } else {
      await writeFile(path, bytes);
      console.log(`wrote ${name} (${bytes.length} bytes)`);
    }
  }
  if (CHECK && drift > 0) {
    throw new Error(
      `${drift} profile-declaration fixture(s) drifted; re-run the generator and review the diff`,
    );
  }
  if (CHECK) console.log("profile-declaration fixtures: byte-stable");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
