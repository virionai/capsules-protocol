#!/usr/bin/env node
// generate-chain-rule-fixtures.mjs
//
// Generates the chain-rules conformance fixtures under
// spec/vectors/chain-rules/output/. These pin the per-event field rules
// in spec/chain.md ("Field rules" + verification steps 6 and 7):
//
//   - The step-6 actor rule is CONDITIONAL on the manifest's own claim.
//     A NON-EMPTY manifest.participants[] binds every event actor to the
//     declared set (or the literal "system:host"), fail-closed. An EMPTY
//     participants[] is the manifest making no claim about who acted — a
//     weaker claim made honestly (template / open-publication tiers) —
//     so verification succeeds and the verifier REPORTS the unbound
//     actor set (actor_set_bound=false plus a note). Conditioning on the
//     list is safe because participants is covered by manifest_hash
//     inside the signed payload: an attacker cannot empty it to escape
//     the check without breaking every envelope signature.
//   - `kind` is a closed enum in EVERY tier: an out-of-enum kind is not
//     a weaker claim, it is unreadable to the foreign LLM reader, so
//     readers reject it unconditionally.
//
// Fixtures (all cryptographically well-formed — real signatures, correct
// manifest hash, correct content index — so a verifier that skips the
// rule under test reports ok=true and fails the registry):
//   actor-not-participant.capsule  participants[] declares human:origin;
//                                  the single event's actor is
//                                  human:mallory. FAIL (chain).
//   unknown-kind.capsule           event kind "gossip", outside the
//                                  closed enum. FAIL (chain).
//   unbound-actors.capsule         participants[] is EMPTY; the single
//                                  event names human:origin anyway.
//                                  ok=true with actor_set_bound=false
//                                  and the unbound-actor-set note.
//   invalid-actor-namespace.capsule participants[] declares
//                                  robot:origin — outside the CLOSED
//                                  actor_id namespace set (manifest.md:
//                                  human/ai/system/capsule). The event
//                                  actor is the same string, so the
//                                  membership rule passes and ONLY the
//                                  namespace grammar decides. FAIL.
//   keys.json                      originator keypair.
//
// The reference builder REFUSES to emit the two failing shapes — that is
// the point of the appendEvent guard — so this generator reaches past
// appendEvent (pushing bare events directly) to synthesize what a
// non-conformant writer would produce.
//
// The private key is a FIXED intentional throwaway TEST key — never a
// production key — so regeneration is byte-stable (deterministic Ed25519
// + fixed timestamps + fixed ZIP date). Fixture -> expected outcome
// lives in spec/vectors/chain-rules/vectors.json. Regeneration is an
// intentional spec change; review the byte-level diff. Pass --check to
// compare generated bytes with the checked-in fixtures.

import { createPublicKey } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { hexToBytes, bytesToHex } from "../src/canonical.js";
import { ed25519PrivateFromRaw, ed25519PublicToRaw } from "../src/crypto.js";
import { buildChainEvents, eventsToJsonl, firstAndEntryHash } from "../src/chain.js";
import {
  buildContentIndex,
  buildManifest,
  buildSignerCommitment,
  computeCapsuleId,
  manifestBytes,
  manifestHash,
} from "../src/manifest.js";
import { buildEnvelope, signEnvelope } from "../src/envelope.js";
import { CapsuleBuilder } from "../src/index.js";
import { packZip } from "../src/zip.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..");
const OUT_DIR = join(REPO_ROOT, "spec", "vectors", "chain-rules", "output");
const CHECK = process.argv.includes("--check");

// FIXED throwaway TEST key (deterministic fixtures). Never a production key.
const ORIGINATOR_PRIVATE_HEX =
  "9e4b7a1d3c5f60e2b8d4a6c0f1e3957b2d4f6a8c0e1b3d5f7a9c1e3b5d7f90a2";

// Deterministic timestamp keeps the fixtures byte-stable across regenerations.
const SIGNED_AT = "2026-08-02T12:00:00Z";

const DECLARED = [{ actor_id: "human:origin", role: "originator", label: "Origin" }];

function keysFromPrivateHex(privateKeyHex) {
  const privateKey = Buffer.from(hexToBytes(privateKeyHex));
  const publicKey = ed25519PublicToRaw(createPublicKey(ed25519PrivateFromRaw(privateKey)));
  return { privateKey, publicKey, privateKeyHex, publicKeyHex: bytesToHex(publicKey) };
}

function newBuilder(keys, participants) {
  const builder = new CapsuleBuilder({
    originator: { publicKey: keys.publicKeyHex, label: "ChainRuleFixture" },
    participants,
    createdAt: SIGNED_AT,
  });
  builder.setProgram("# Chain Rule Fixture\n\nOne event, one field rule under test.\n");
  return builder;
}

function bareEvent(overrides = {}) {
  return {
    actor: "human:origin",
    kind: "decision",
    action: "approved",
    target: "program.md",
    timestamp: SIGNED_AT,
    payload: { amount: 4242, note: "chain-rules fixture event" },
    ...overrides,
  };
}

async function seal(builder, keys) {
  return Buffer.from(
    await builder.seal({
      signers: [
        { role: "originator", publicKey: keys.publicKey, privateKey: keys.privateKey },
      ],
      signedAt: SIGNED_AT,
    }),
  );
}

/**
 * Low-level single-event capsule for shapes the CapsuleBuilder refuses to
 * emit at construction/seal time (not just at appendEvent) — currently
 * the out-of-namespace participant declaration. Mirrors the builder's
 * plain path exactly: real signature, correct manifest hash, correct
 * content index, so ONLY the rule under test decides the outcome.
 */
async function buildLowLevelCapsule(keys, { participants, event }) {
  const events = buildChainEvents([event]);
  const { firstEventHash, entryHash } = firstAndEntryHash(events);
  const files = new Map();
  files.set(
    "program.md",
    Buffer.from("# Chain Rule Fixture\n\nOne event, one field rule under test.\n", "utf8"),
  );
  files.set("chain/events.jsonl", eventsToJsonl(events));
  const contentIndex = buildContentIndex(files);
  const manifest = buildManifest({
    originator: { public_key: keys.publicKeyHex, label: "ChainRuleFixture" },
    participants,
    contentIndex,
    firstEventHash,
    encryption: null,
    createdAt: SIGNED_AT,
    signerCommitment: buildSignerCommitment([
      { role: "originator", public_key: keys.publicKeyHex },
    ]),
  });
  const capsuleId = computeCapsuleId(keys.publicKey, firstEventHash);
  manifest.id = capsuleId;
  const envelope = buildEnvelope({
    capsuleId,
    firstEventHash,
    entryHash,
    manifestHash: manifestHash(manifest),
    contentIndexHash: contentIndex.index_hash,
    encryptedBlobHash: null,
    cipher: "none",
    signedAt: SIGNED_AT,
  });
  signEnvelope(envelope, [
    { role: "originator", publicKey: keys.publicKey, privateKey: keys.privateKey },
  ]);
  const all = new Map(files);
  all.set("manifest.json", manifestBytes(manifest));
  all.set("provenance/envelope.json", Buffer.from(JSON.stringify(envelope, null, 2), "utf8"));
  return Buffer.from(await packZip(all));
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  const originator = keysFromPrivateHex(ORIGINATOR_PRIVATE_HEX);

  // (1) actor-not-participant: participants[] is declared and NON-EMPTY,
  // but the event's actor is not in it (and is not system:host). The
  // builder's appendEvent guard rejects this by design, so push the bare
  // event straight onto the queue; seal() hashes and signs it normally.
  const actorBuilder = newBuilder(originator, DECLARED);
  actorBuilder.bareEvents.push(bareEvent({ actor: "human:mallory" }));
  const actorNotParticipant = await seal(actorBuilder, originator);

  // (2) unknown-kind: a kind outside the closed enum. Same bypass.
  const kindBuilder = newBuilder(originator, DECLARED);
  kindBuilder.bareEvents.push(bareEvent({ kind: "gossip" }));
  const unknownKind = await seal(kindBuilder, originator);

  // (3) unbound-actors (positive control): participants[] is EMPTY and
  // the event names an actor anyway. This is a LEGAL weaker claim — the
  // builder accepts it through the front door — and verifiers MUST
  // verify it while reporting the unbound actor set.
  const unboundBuilder = newBuilder(originator, []);
  unboundBuilder.appendEvent(bareEvent());
  const unboundActors = await seal(unboundBuilder, originator);

  // (4) non-contiguous-seq: the single event carries seq=2 (bare-event
  // fields override the builder's assignment), correctly hashed and
  // signed — so ONLY spec/chain.md verification step 5 ("seq is strictly
  // monotonic from 1") decides it. A verifier that trusts the stored seq
  // or only counts events reports ok=true and fails the registry.
  const seqBuilder = newBuilder(originator, DECLARED);
  seqBuilder.bareEvents.push(bareEvent({ seq: 2 }));
  const nonContiguousSeq = await seal(seqBuilder, originator);

  // (5) participant-without-label (positive control): the declared
  // participant carries only actor_id + role. The base spec requires
  // actor_id (pattern) and nothing else — `label` is advisory — so this
  // MUST verify with the actor set bound. A lane whose typed manifest
  // view demands `label` refuses a spec-valid capsule (addendum A12).
  const noLabelBuilder = newBuilder(originator, [
    { actor_id: "human:origin", role: "originator" },
  ]);
  noLabelBuilder.appendEvent(bareEvent());
  const participantWithoutLabel = await seal(noLabelBuilder, originator);

  // (7) invalid-actor-namespace: the DECLARED participant's actor_id uses
  // a namespace outside the closed manifest.md set (human/ai/system/
  // capsule). The event names the same actor, so the step-6 membership
  // rule passes and only the namespace grammar decides the outcome. The
  // builder refuses this shape at construction/seal, so it is built
  // through the low-level path — what a non-conformant writer produces.
  const invalidActorNamespace = await buildLowLevelCapsule(originator, {
    participants: [{ actor_id: "robot:origin", role: "originator", label: "Origin" }],
    event: bareEvent({ actor: "robot:origin" }),
  });

  // (6) invalid-untrusted-path: untrusted_payload_fields carries an entry
  // outside the normative grammar (chain.md "Untrusted content":
  // payload(.segment)+). Correctly hashed and signed — the marking is
  // covered by the event hash — so only the grammar rule decides it. An
  // unparseable marking silently unmarks content for every host.
  const untrustedBuilder = newBuilder(originator, DECLARED);
  untrustedBuilder.bareEvents.push(
    bareEvent({ untrusted_payload_fields: ["not-payload.note"] }),
  );
  const invalidUntrustedPath = await seal(untrustedBuilder, originator);

  const keys = {
    originator: {
      publicKey: originator.publicKeyHex,
      privateKey: originator.privateKeyHex,
    },
  };

  const artifacts = [
    ["actor-not-participant.capsule", actorNotParticipant],
    ["unknown-kind.capsule", unknownKind],
    ["unbound-actors.capsule", unboundActors],
    ["non-contiguous-seq.capsule", nonContiguousSeq],
    ["participant-without-label.capsule", participantWithoutLabel],
    ["invalid-untrusted-path.capsule", invalidUntrustedPath],
    ["invalid-actor-namespace.capsule", invalidActorNamespace],
    ["keys.json", Buffer.from(JSON.stringify(keys, null, 2) + "\n", "utf8")],
  ];

  let drift = 0;
  for (const [name, bytes] of artifacts) {
    const path = join(OUT_DIR, name);
    if (CHECK) {
      let checkedIn;
      try {
        checkedIn = await readFile(path);
      } catch (err) {
        throw new Error(`${name}: checked-in fixture missing or unreadable: ${err.message}`);
      }
      if (!checkedIn.equals(bytes)) {
        console.error(`DRIFT: ${name} differs from deterministic generator output`);
        drift++;
      } else {
        console.log(`ok ${name}`);
      }
    } else {
      await writeFile(path, bytes);
      console.log(`wrote ${name} (${bytes.length} bytes)`);
    }
  }
  if (CHECK && drift > 0) {
    throw new Error(`${drift} chain-rules fixture(s) drifted; re-run the generator and review the diff`);
  }
  if (CHECK) console.log("chain-rules fixtures: byte-stable");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
