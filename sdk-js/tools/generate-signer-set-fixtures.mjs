#!/usr/bin/env node
// generate-signer-set-fixtures.mjs
//
// Generates the signer-set binding conformance fixtures under
// spec/vectors/signer-set/output/. These pin the normative rules in
// spec/manifest.md ("signer_commitment") and spec/envelope.md ("Signer
// set binding"):
//
//   - PRESENCE BINDS: when manifest.signer_commitment is present, the
//     normalized envelope signer set MUST equal it exactly. Stripping a
//     signer, appending a fresh signature in a chosen role, swapping
//     roles, or presenting an unsorted commitment all fail closed.
//   - ABSENCE REPORTS: a manifest without the commitment verifies, and
//     the verifier reports the signer set as unbound machine-readably.
//   - Duplicate (role, public_key) signer entries are malformed.
//   - Originator binding: manifest.originator.public_key MUST have a
//     valid envelope signature with role "originator".
//
// Fixtures:
//   bound-two-signers.capsule      originator+approver, committed. ok=true.
//   commitment-absent.capsule      no signer_commitment. ok=true, unbound.
//   commitment-strip.capsule       approver removed from signers[]. FAIL.
//   commitment-add.capsule         fresh attacker signature in role
//                                  "notary" appended. FAIL (the forged
//                                  signature itself verifies!).
//   commitment-duplicate.capsule   originator entry duplicated. FAIL.
//   commitment-role-swap.capsule   same two keys re-signed under each
//                                  other's roles. FAIL.
//   commitment-unsorted.capsule    honest membership, wrong sort order.
//                                  FAIL (ordering is normative).
//   originator-not-a-signer.capsule originator key signed only as
//                                  "creator", committed as such. FAIL.
//   keys.json                      originator/approver/attacker keypairs.
//
// The private keys are FIXED intentional throwaway TEST keys — never
// production keys — so regeneration is byte-stable (deterministic
// Ed25519 + fixed timestamps + fixed ZIP date). Fixture -> expected
// outcome lives in spec/vectors/signer-set/vectors.json. Regeneration is
// an intentional spec change; review the byte-level diff. Pass --check
// to compare generated bytes with the checked-in fixtures.

import { createPublicKey } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { hexToBytes, bytesToHex } from "../src/canonical.js";
import { ed25519PrivateFromRaw, ed25519PublicToRaw, ed25519Sign } from "../src/crypto.js";
import { buildChainEvents, eventsToJsonl, firstAndEntryHash } from "../src/chain.js";
import {
  buildContentIndex,
  buildManifest,
  buildSignerCommitment,
  computeCapsuleId,
  manifestBytes,
  manifestHash,
} from "../src/manifest.js";
import { buildEnvelope, signEnvelope, envelopeSigningInput } from "../src/envelope.js";
import { CapsuleBuilder } from "../src/builder.js";
import { packZip, unpackZip } from "../src/zip.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..");
const OUT_DIR = join(REPO_ROOT, "spec", "vectors", "signer-set", "output");
const CHECK = process.argv.includes("--check");

// FIXED throwaway TEST keys (deterministic fixtures). Never production keys.
const PRIVATE_HEX = {
  originator: "aa0f3a26b41c8d715356d24054f2b1cbcddbea94b7d3b3bd60cbe08a2c2f7112",
  approver: "b7d0e5f1c0a94ed35c7e19a44c1a7e02246cb0fb04d0f1e73a889d5c33b40921",
  attacker: "c3e88a9f5b2d41c6a90e7fd21b7c39a45d10e6b98f24c7d0a3b5e19c60d8f437",
};

// Deterministic timestamps keep the fixtures byte-stable across regenerations.
const SIGNED_AT = "2026-08-01T12:00:00Z";

function keysFromPrivateHex(privateKeyHex) {
  const privateKey = Buffer.from(hexToBytes(privateKeyHex));
  const publicKey = ed25519PublicToRaw(createPublicKey(ed25519PrivateFromRaw(privateKey)));
  return { privateKey, publicKey, privateKeyHex, publicKeyHex: bytesToHex(publicKey) };
}

/** The committed two-signer base capsule, built through the SDK builder. */
async function buildBoundCapsule(originator, approver) {
  const builder = new CapsuleBuilder({
    originator: { publicKey: originator.publicKeyHex, label: "SignerSetOriginator" },
    participants: [
      { actor_id: "human:origin", role: "originator", label: "Origin" },
      { actor_id: "human:approver", role: "approver", label: "Approver" },
    ],
    createdAt: SIGNED_AT,
  });
  builder.setProgram("# Signer Set Fixture\n\nTwo committed signers.\n");
  builder.appendEvent({
    actor: "human:origin",
    kind: "decision",
    action: "approved",
    target: "program.md",
    timestamp: SIGNED_AT,
    payload: { note: "signer-set conformance fixture" },
  });
  const bytes = await builder.seal({
    signers: [
      { role: "originator", publicKey: originator.publicKey, privateKey: originator.privateKey },
      { role: "approver", publicKey: approver.publicKey, privateKey: approver.privateKey },
    ],
    signedAt: SIGNED_AT,
  });
  return Buffer.from(bytes);
}

/**
 * Low-level single-signer capsule for the absent / unsorted /
 * originator-binding cases, where the builder's own emission and
 * validation must be bypassed.
 *
 * `signerCommitment`: undefined = omit the member entirely; otherwise
 * stored verbatim (even when deliberately malformed).
 */
async function buildLowLevelCapsule({ signerKeys, role, signerCommitment, extraSigners = [] }) {
  const events = buildChainEvents([
    {
      actor: "human:origin",
      kind: "decision",
      action: "approved",
      target: "program.md",
      timestamp: SIGNED_AT,
      payload: { note: "signer-set conformance fixture" },
    },
  ]);
  const { firstEventHash, entryHash } = firstAndEntryHash(events);
  const files = new Map();
  files.set("program.md", Buffer.from("# Signer Set Fixture\n\nLow-level build.\n", "utf8"));
  files.set("chain/events.jsonl", eventsToJsonl(events));
  const contentIndex = buildContentIndex(files);
  const manifest = buildManifest({
    originator: { public_key: signerKeys.publicKeyHex, label: "SignerSetOriginator" },
    participants: [{ actor_id: "human:origin", role: "originator", label: "Origin" }],
    contentIndex,
    firstEventHash,
    skillTrust: {},
    encryption: null,
    createdAt: SIGNED_AT,
    signerCommitment,
  });
  const capsuleId = computeCapsuleId(signerKeys.publicKey, firstEventHash);
  manifest.id = capsuleId;
  const envelope = buildEnvelope({
    capsuleId,
    firstEventHash,
    entryHash,
    manifestHash: manifestHash(manifest),
    contentIndexHash: contentIndex.index_hash,
    encryptedBlobHash: null,
    cipher: "none",
    signedAt: SIGNED_AT,
  });
  signEnvelope(envelope, [
    { role, publicKey: signerKeys.publicKey, privateKey: signerKeys.privateKey },
    ...extraSigners,
  ]);
  const all = new Map(files);
  all.set("manifest.json", manifestBytes(manifest));
  all.set("provenance/envelope.json", Buffer.from(JSON.stringify(envelope, null, 2), "utf8"));
  return Buffer.from(await packZip(all));
}

/** Rewrite provenance/envelope.json inside a capsule via `mutate(env)`. */
async function rewriteEnvelope(capsuleBytes, mutate) {
  const files = await unpackZip(capsuleBytes);
  const env = JSON.parse(Buffer.from(files.get("provenance/envelope.json")).toString("utf8"));
  mutate(env);
  files.set("provenance/envelope.json", Buffer.from(JSON.stringify(env, null, 2), "utf8"));
  return Buffer.from(await packZip(files));
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  const originator = keysFromPrivateHex(PRIVATE_HEX.originator);
  const approver = keysFromPrivateHex(PRIVATE_HEX.approver);
  const attacker = keysFromPrivateHex(PRIVATE_HEX.attacker);

  // (1) Positive control: two committed signers.
  const bound = await buildBoundCapsule(originator, approver);

  // (2) Absent commitment: verifies, reported as unbound.
  const absent = await buildLowLevelCapsule({
    signerKeys: originator,
    role: "originator",
    signerCommitment: undefined,
  });

  // (3) Strip: the approver's signature removed without residue in the
  // array itself — the commitment names the missing member.
  const strip = await rewriteEnvelope(bound, (env) => {
    env.signers = env.signers.filter((s) => s.role !== "approver");
  });

  // (4) Add: a fresh, VALID attacker signature appended in a chosen role.
  const add = await rewriteEnvelope(bound, (env) => {
    const sig = ed25519Sign(attacker.privateKey, envelopeSigningInput(env, "notary"));
    env.signers.push({
      role: "notary",
      public_key: attacker.publicKeyHex,
      signature: bytesToHex(sig),
    });
  });

  // (5) Duplicate: an existing entry copied verbatim.
  const duplicate = await rewriteEnvelope(bound, (env) => {
    env.signers.push({ ...env.signers.find((s) => s.role === "originator") });
  });

  // (6) Role swap: both committed keys re-sign under each other's roles.
  // Every signature verifies; the set no longer matches the commitment.
  const roleSwap = await rewriteEnvelope(bound, (env) => {
    const reSign = (role, keys) => ({
      role,
      public_key: keys.publicKeyHex,
      signature: bytesToHex(ed25519Sign(keys.privateKey, envelopeSigningInput(env, role))),
    });
    env.signers = [reSign("approver", originator), reSign("originator", approver)];
  });

  // (7) Unsorted commitment: honest membership, wrong order. The
  // commitment is bound by its stored bytes, so ordering is normative.
  const sortedMembers = buildSignerCommitment([
    { role: "originator", public_key: originator.publicKeyHex },
    { role: "approver", public_key: approver.publicKeyHex },
  ]);
  const unsorted = await buildLowLevelCapsule({
    signerKeys: originator,
    role: "originator",
    signerCommitment: [...sortedMembers].reverse(),
    extraSigners: [
      { role: "approver", publicKey: approver.publicKey, privateKey: approver.privateKey },
    ],
  });

  // (8) Originator-not-a-signer: the originator key signs only as
  // "creator" (and commits to that), so the signer set matches its
  // commitment — the ORIGINATOR BINDING invariant is what fails.
  const originatorNotASigner = await buildLowLevelCapsule({
    signerKeys: originator,
    role: "creator",
    signerCommitment: buildSignerCommitment([
      { role: "creator", public_key: originator.publicKeyHex },
    ]),
  });

  const keys = {
    originator: { publicKey: originator.publicKeyHex, privateKey: originator.privateKeyHex },
    approver: { publicKey: approver.publicKeyHex, privateKey: approver.privateKeyHex },
    attacker: { publicKey: attacker.publicKeyHex, privateKey: attacker.privateKeyHex },
  };

  const artifacts = [
    ["bound-two-signers.capsule", bound],
    ["commitment-absent.capsule", absent],
    ["commitment-strip.capsule", strip],
    ["commitment-add.capsule", add],
    ["commitment-duplicate.capsule", duplicate],
    ["commitment-role-swap.capsule", roleSwap],
    ["commitment-unsorted.capsule", unsorted],
    ["originator-not-a-signer.capsule", originatorNotASigner],
    ["keys.json", Buffer.from(JSON.stringify(keys, null, 2) + "\n", "utf8")],
  ];

  let drift = 0;
  for (const [name, bytes] of artifacts) {
    const path = join(OUT_DIR, name);
    if (CHECK) {
      let checkedIn;
      try {
        checkedIn = await readFile(path);
      } catch (err) {
        throw new Error(`${name}: checked-in fixture missing or unreadable: ${err.message}`);
      }
      if (!checkedIn.equals(bytes)) {
        console.error(`DRIFT: ${name} differs from deterministic generator output`);
        drift++;
      } else {
        console.log(`ok ${name}`);
      }
    } else {
      await writeFile(path, bytes);
      console.log(`wrote ${name} (${bytes.length} bytes)`);
    }
  }
  if (CHECK && drift > 0) {
    throw new Error(`${drift} signer-set fixture(s) drifted; re-run the generator and review the diff`);
  }
  if (CHECK) console.log("signer-set fixtures: byte-stable");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
